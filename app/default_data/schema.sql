-- =========================================================
-- ORDER
-- =========================================================
CREATE TABLE LINEAGE_TEST_ORDER (
  ORDER_ID NUMBER,
  ORDER_NO VARCHAR2(30) NOT NULL,
  CUSTOMER_ID NUMBER NOT NULL,
  ORDER_DT DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
  STATUS_CD VARCHAR2(20) DEFAULT 'NEW' NOT NULL,
  CURRENCY_CD CHAR(3) DEFAULT 'EUR' NOT NULL,
  BILLING_NAME VARCHAR2(200),
  BILLING_STREET1 VARCHAR2(200),
  BILLING_CITY VARCHAR2(120),
  BILLING_POSTAL_CODE VARCHAR2(20),
  BILLING_COUNTRY_CD CHAR(2),
  SHIPPING_NAME VARCHAR2(200),
  SHIPPING_STREET1 VARCHAR2(200),
  SHIPPING_STREET2 VARCHAR2(200),
  SHIPPING_CITY VARCHAR2(120),
  SHIPPING_POSTAL_CODE VARCHAR2(20),
  SHIPPING_COUNTRY_CD CHAR(2),
  PAYMENT_METHOD VARCHAR2(30),
  PAYMENT_TXN_ID VARCHAR2(80),
  PAID_AT TIMESTAMP,
  SHIPPING_METHOD VARCHAR2(30),
  TRACKING_NO VARCHAR2(60),
  SHIPPED_AT TIMESTAMP,
  DELIVERED_AT TIMESTAMP,
  SUBTOTAL_AMT NUMBER(12,2) DEFAULT 0 NOT NULL,
  TAX_AMT NUMBER(12,2) DEFAULT 0 NOT NULL,
  SHIPPING_COST NUMBER(12,2) DEFAULT 0 NOT NULL,
  TOTAL_DISCOUNT_AMT NUMBER(12,2) DEFAULT 0 NOT NULL,
  TOTAL_AMT NUMBER(12,2) DEFAULT 0 NOT NULL,
  CHANNEL_CD VARCHAR2(20) DEFAULT 'WEB' NOT NULL,
  COUPON_CD VARCHAR2(30),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP,
  CONSTRAINT PK_LINEAGE_TEST_ORDER PRIMARY KEY (ORDER_ID),
  CONSTRAINT UK_LINEAGE_TEST_ORDER_NO UNIQUE (ORDER_NO),
  CONSTRAINT FK_LINEAGE_TEST_ORDER_CUST FOREIGN KEY (CUSTOMER_ID)
    REFERENCES LINEAGE_TEST_CUSTOMER (CUSTOMER_ID),
  CONSTRAINT CK_LINEAGE_TEST_ORDER_STATUS CHECK (STATUS_CD IN ('NEW','PAID','SHIPPED','CANCELLED')),
  CONSTRAINT CK_LINEAGE_TEST_ORDER_CURR CHECK (REGEXP_LIKE(CURRENCY_CD, '^[A-Z]{3}$')),
  CONSTRAINT CK_LINEAGE_TEST_ORDER_CHANNEL CHECK (CHANNEL_CD IN ('WEB','MOBILE','STORE','API')),
  CONSTRAINT CK_LINEAGE_TEST_ORDER_PAYMETHOD CHECK (PAYMENT_METHOD IS NULL OR PAYMENT_METHOD IN ('CARD','SEPA','PAYPAL','BANK_TRANSFER')),
  CONSTRAINT CK_LINEAGE_TEST_ORDER_SHIPMETHOD CHECK (SHIPPING_METHOD IS NULL OR SHIPPING_METHOD IN ('STANDARD','EXPRESS','PICKUP'))
);
CREATE INDEX IX_LINEAGE_TEST_ORDER_CUST ON LINEAGE_TEST_ORDER (CUSTOMER_ID);
CREATE INDEX IX_LINEAGE_TEST_ORDER_DT ON LINEAGE_TEST_ORDER (ORDER_DT);

