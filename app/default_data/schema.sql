CREATE TABLE LINEAGE_TEST_ORDER_ITEM (
  ORDER_ITEM_ID NUMBER,
  ORDER_ID NUMBER NOT NULL,
  LINE_NO NUMBER(6) NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  QTY NUMBER(12,3) NOT NULL,
  UNIT_PRICE NUMBER(12,2) NOT NULL,
  DISCOUNT_AMT NUMBER(12,2) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP,
  CONSTRAINT PK_LINEAGE_TEST_ORDER_ITEM PRIMARY KEY (ORDER_ITEM_ID),
  CONSTRAINT UK_LINEAGE_TEST_ORDER_ITEM_LINE UNIQUE (ORDER_ID, LINE_NO),
  CONSTRAINT FK_LINEAGE_TEST_OI_ORDER FOREIGN KEY (ORDER_ID)
    REFERENCES LINEAGE_TEST_ORDER (ORDER_ID),
  CONSTRAINT FK_LINEAGE_TEST_OI_PROD FOREIGN KEY (PRODUCT_ID)
    REFERENCES LINEAGE_TEST_PRODUCT (PRODUCT_ID),
  CONSTRAINT CK_LINEAGE_TEST_OI_QTY CHECK (QTY > 0),
  CONSTRAINT CK_LINEAGE_TEST_OI_PRICE CHECK (UNIT_PRICE >= 0),
  CONSTRAINT CK_LINEAGE_TEST_OI_DISC CHECK (DISCOUNT_AMT >= 0)
